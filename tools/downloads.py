#!/usr/bin/env python3
"""Regenerate renders/DOWNLOADS.md — a LOCAL (gitignored) download sheet listing
every episode that rendered successfully in GitHub CI, with its artifact + the
exact `gh run download` command. Re-run this after each successful render.

    python tools/downloads.py
"""
import json, re, subprocess, pathlib, glob

REPO = "cornel-stack/faceless-finance"
ROOT = pathlib.Path(__file__).resolve().parent.parent


def gh_json(args):
    out = subprocess.run(["gh"] + args, capture_output=True, text=True, cwd=ROOT)
    return json.loads(out.stdout) if out.stdout.strip() else None


def episode_title(epid):
    for f in glob.glob(str(ROOT / f"episodes/examples/{epid}-*.json")):
        try:
            return json.load(open(f)).get("title", "")
        except Exception:
            pass
    return ""


runs = gh_json(["run", "list", "--workflow", "Render episode", "--limit", "60",
                "--json", "databaseId,headBranch,conclusion,status,number,createdAt"]) or []

rows = {}  # epid -> row (keep the newest successful run per episode)
for r in runs:
    # The TRUE episode id comes from the artifact name (e.g. "EP013-30"), NOT the
    # branch — several episodes are rendered from one cumulative branch, so the
    # branch (e.g. ep031-theranos) does not identify the episode.
    if r.get("status") != "completed" or r.get("conclusion") != "success":
        continue
    run_id = r["databaseId"]
    arts = gh_json(["api", f"repos/{REPO}/actions/runs/{run_id}/artifacts"]) or {}
    art = (arts.get("artifacts") or [{}])[0]
    art_name = art.get("name", "")
    m = re.match(r"(EP\d{3,})-\d+", art_name)
    if m:
        epid = m.group(1)
    else:
        # fall back to the branch name if the artifact is missing/unnamed
        bm = re.match(r"ep(\d{3,})", r.get("headBranch", ""))
        if not bm:
            continue
        epid = "EP" + bm.group(1)
    if epid in rows:
        continue  # runs are newest-first; keep first (newest) success
    rows[epid] = {
        "epid": epid,
        "title": episode_title(epid),
        "run_id": run_id,
        "run_url": f"https://github.com/{REPO}/actions/runs/{run_id}",
        "artifact": art.get("name", ""),
        "mb": round(art.get("size_in_bytes", 0) / 1048576) if art else 0,
        "expires": (art.get("expires_at", "") or "")[:10],
    }

ordered = sorted(rows.values(), key=lambda x: x["epid"])
lines = [
    "# Napkin Numbers — rendered videos (download sheet)",
    "",
    "Local, auto-generated by `python tools/downloads.py`. Re-run to refresh.",
    "Each artifact bundles `<EPID>.mp4` + the `youtube/` package (thumbnail, title,",
    "description, chapters, tags). Artifacts expire ~14 days after the render.",
    "",
    f"**{len(ordered)} videos rendered.**",
    "",
    "| Ep | Title | Download (CLI) | Browser | Artifact | Expires |",
    "|----|-------|----------------|---------|----------|---------|",
]
for r in ordered:
    cli = f"`gh run download {r['run_id']} -n {r['artifact']}`" if r["artifact"] else "—"
    lines.append(
        f"| {r['epid']} | {r['title']} | {cli} | [run]({r['run_url']}) | {r['artifact']} ({r['mb']}MB) | {r['expires']} |"
    )
lines.append("")
lines.append("To grab everything at once, run each CLI command from the repo root.")
lines.append("")

out = ROOT / "renders" / "DOWNLOADS.md"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(lines))
print(f"wrote {out}  ({len(ordered)} videos)")
for r in ordered:
    print(f"  {r['epid']}: {r['artifact']}  ({r['mb']}MB, expires {r['expires']})")
